/** Character design in an isolated browser; no user files or live model calls. */
import assert from 'node:assert/strict';
import path from 'node:path';
import { withChatHarness } from './_chat-harness.mjs';

await withChatHarness({ tag: 'agent-card', papers: [] }, async h => {
  const { page, pass, scratch } = h;
  const input = async (selector, value) => page.$eval(selector, (node, value) => {
    node.value = value; node.dispatchEvent(new Event('input', { bubbles: true }));
  }, value);
  const saved = () => page.evaluate(() => JSON.parse(localStorage.getItem('reader.agent.profile.v1') || 'null'));
  const visible = selector => page.waitForSelector(selector, { visible: true });
  const idle = () => page.waitForFunction(() => document.querySelector('#agentProfileForm').getAttribute('aria-busy') === 'false');
  const generateMarker = '只输出 JSON 对象';
  const card = { name: 'Mira', personality: 'Warm but direct', gender: 'Female', habits: 'Brief answers',
    description: 'A patient friend who loves music.\n'.repeat(30).trim(), examples: 'User: I am stuck.\nAssistant: Let us try one step.', enabled: false, customized: true };
  const finishGeneration = async value => {
    await h.waitRequest(generateMarker);
    await h.emit(generateMarker, { text: value, done: true }); await idle();
  };
  const frame = () => page.$eval('.settings-box', node => {
    const { x, y, width, height } = node.getBoundingClientRect(); return { x, y, width, height };
  });
  const choice = async index => (await page.$$('#agentCardChoices button'))[index].click();

  await visible('#agentWelcome');
  await page.click('#agentWelcomeSkip');
  assert.equal(await saved(), null);
  await page.reload({ waitUntil: 'networkidle0' });
  assert.equal(await page.$('#agentWelcome'), null);
  pass('first-open invitation can be skipped without saving a card or repeating on reload');

  await page.evaluate(() => localStorage.removeItem('reader.agent.welcome.v1'));
  await page.reload({ waitUntil: 'networkidle0' });
  await page.click('#agentWelcomeCustomize');
  await visible('#settingsPaneAgent:not(.hidden)');
  assert.equal(await page.$eval('#agentRoleEnabled', node => node.checked), false);
  assert.equal(await page.$eval('#agentNameDisplay', node => node.tagName), 'SPAN');
  await visible('#agentCustomize');
  assert.match(await page.$eval('#agentPersonalityInput', node => node.value), /Warm/);
  assert.equal(await page.$eval('#agentCardEditor', node => node.hidden), true);
  assert.equal(await page.$eval('#agentCardBuilder', node => node.hidden), true);
  const overviewFrame = await frame();
  assert.ok(overviewFrame.width >= 950, 'Settings uses the larger desktop frame');
  await page.screenshot({ path: path.join(scratch, 'customize.png') });
  pass('new users see one Customize card in Settings instead of an exposed form');

  await page.click('#agentCustomize');
  await visible('#agentCardBuilder');
  assert.deepEqual(await frame(), overviewFrame);
  assert.equal(await page.$eval('#agentCardQuestion', node => node.textContent), 'What kind of personality would you like me to have?');
  assert.equal(await page.$$eval('#agentCardChoices button', nodes => nodes.length), 4);
  assert.equal(await page.$eval('#agentCardNext', node => node.disabled), true);
  await page.evaluate(async () => { (await import('/js/ai.js')).Settings.data.hasApiKey = false; });
  await choice(0);
  await input('#agentCardInput', 'Warm, playful and independent.');
  await page.click('#agentCardNext');
  assert.match(await page.$eval('#agentCardQuestion', node => node.textContent), /What tone/);
  await page.click('#agentCardPrevious');
  assert.equal(await page.$eval('#agentCardInput', node => node.value), 'Warm, playful and independent.');
  await choice(3);
  await input('#agentCardInput', 'PREFERENCE_MARKER: honest and independent.');
  await page.click('#agentCardNext');
  await page.click('#agentCardGenerate');
  assert.match(await page.$eval('#agentCardConversation', node => node.textContent), /one step before we can chat/);
  assert.equal(await page.$eval('#agentCardStatus', node => node.classList.contains('error')), false);
  assert.equal(await page.evaluate(() => __mockChatRequests.length), 0);
  await page.click('#agentCardConversation button');
  await page.waitForFunction(() => document.activeElement.id === 'cfgApiKey');
  await page.click('#settingsNavAgent');
  await visible('#agentCardBuilder');
  assert.match(await page.$eval('#agentCardQuestion', node => node.textContent), /What tone/);
  await page.evaluate(async () => { (await import('/js/ai.js')).Settings.data.hasApiKey = true; });
  await page.$eval('.settings-panes', node => { node.scrollTop = 0; });
  await page.screenshot({ path: path.join(scratch, 'ai-design.png') });
  pass('choices and custom answers advance one question, Back edits answers, and no-key generation preserves progress');

  await choice(0); await page.click('#agentCardNext');
  await choice(0); await page.click('#agentCardNext');
  await input('#agentCardInput', 'Mira'); await page.click('#agentCardNext');
  await choice(1); await page.click('#agentCardNext');
  await page.click('#agentCardSkip');
  await choice(0); await page.click('#agentCardNext');
  await choice(0); await page.click('#agentCardNext');
  await visible('#agentCardReview');
  assert.equal(await page.evaluate(() => __mockChatRequests.length), 0);
  assert.equal(await page.$$eval('#agentReviewAnswers button', nodes => nodes.length), 8);
  await input('#agentCardInput', 'Avoid pet names; I want a friend who loves music.');
  await page.click('#agentCardPrevious');
  await page.click('#agentCardNext');
  assert.match(await page.$eval('#agentCardInput', node => node.value), /Avoid pet names/);
  await page.screenshot({ path: path.join(scratch, 'review.png') });
  await page.evaluate(() => localStorage.setItem('reader.responseLanguage', 'zh-CN'));
  await page.click('#agentCardGenerate'); await finishGeneration(JSON.stringify({ ...card, enabled: true }));
  await visible('#agentCardEditor');
  assert.deepEqual(await frame(), overviewFrame);
  assert.equal(await page.$eval('#agentNameInput', node => node.value), 'Mira');
  assert.equal(await page.$eval('#agentRoleEnabled', node => node.checked), false);
  assert.equal(await saved(), null);
  const generation = await page.evaluate(marker => __mockChatRequests.find(r => r.source.includes(marker)).body, generateMarker);
  assert.equal(generation.messages.filter(message => message.role === 'assistant').length, 8);
  assert.equal(await page.evaluate(() => __mockChatRequests.length), 1);
  assert.ok(JSON.stringify(generation.messages).includes('Avoid pet names'));
  assert.ok(JSON.stringify(generation.messages).includes('honest and independent'));
  assert.ok(!JSON.stringify(generation.messages).includes('Warm, playful and independent'));
  assert.ok(!generation.messages[0].content.includes('Assistant expression preferences'));
  assert.match(generation.messages[0].content, /Character card language: English/);
  assert.match(generation.messages[0].content, /Response language: English/);
  assert.doesNotMatch(generation.messages[0].content, /Response language: Simplified Chinese/);
  assert.equal(await page.$eval('#agentDescriptionInput', node => node.scrollHeight <= node.clientHeight + 1 && node.clientHeight > 240), true);
  pass('only Generate sends the full revised interview, skipped answers and final notes, then opens an editable draft');

  await input('#agentHabitsInput', 'Brief answers; honest disagreements.');
  card.habits = 'Brief answers; honest disagreements.';
  await page.$eval('#agentRoleEnabled', node => { node.checked = true; node.dispatchEvent(new Event('input', { bubbles: true })); });
  await page.click('#agentProfileSave'); await idle();
  card.enabled = true;
  assert.deepEqual(await saved(), card);
  await visible('#agentExistingCard');
  assert.equal(await page.$eval('#agentCustomize', node => node.hidden), true);
  await page.screenshot({ path: path.join(scratch, 'saved-overview.png') });
  await page.click('#agentViewCard'); await visible('#agentCardEditor');
  await page.$eval('.settings-panes', node => { node.scrollTop = 0; });
  await page.screenshot({ path: path.join(scratch, 'character-card.png') });
  await input('#agentNameInput', 'Unsaved name');
  await page.click('#agentProfileReset');
  await visible('#agentExistingCard');
  assert.equal(await page.$eval('#agentNameInput', node => node.value), 'Mira');
  pass('saved cards show Design with AI and View character card; direct edits can be saved or discarded');

  await page.click('#agentDesign');
  await input('#agentCardInput', 'PASTED_CONVERSATION: a dry sense of humor, concise replies.');
  await page.click('#agentCardGenerate'); await finishGeneration('{broken');
  assert.match(await page.$eval('#agentCardStatus', node => node.textContent), /invalid card/);
  assert.deepEqual(await saved(), card);
  await page.click('#agentCardGenerate');
  await visible('#agentCardStop');
  assert.equal(await page.$eval('#agentCardStop', node => node.textContent), 'Stop');
  await page.click('#agentCardStop'); await idle();
  await page.click('#agentCardGenerate'); await finishGeneration(JSON.stringify({ ...card, name: 'Unsaved' }));
  assert.equal(await page.$eval('#agentNameInput', node => node.value), 'Unsaved');
  const direct = await page.evaluate(marker => __mockChatRequests.find(r => r.source.includes(marker)).body, 'PASTED_CONVERSATION');
  assert.equal(direct.messages.filter(message => message.role === 'assistant').length, 1);
  assert.equal(await page.$eval('#agentRoleEnabled', node => node.checked), true);
  await page.click('#agentProfileReset');
  pass('pasted preferences can generate early; invalid JSON and cancellation preserve the saved card and permit retry');

  await page.click('#agentDesign');
  await input('#agentCardInput', 'CLOSE_DURING_GENERATION');
  await page.click('#agentCardGenerate'); await visible('#agentCardStop');
  await page.click('#closeSettings'); await page.waitForSelector('#settingsModal.hidden');
  await page.click('#settingsBtn'); await visible('#settingsModal:not(.hidden)');
  await visible('#agentExistingCard');
  assert.equal(await page.$eval('#agentNameInput', node => node.value), 'Mira');
  assert.equal(await page.$eval('#agentCardStop', node => node.hidden), true);
  await page.$eval('#agentRoleEnabled', node => { node.checked = false; node.dispatchEvent(new Event('input', { bubbles: true })); });
  await page.click('#agentProfileSave'); await idle();
  card.enabled = false; assert.deepEqual(await saved(), card);
  await page.click('#closeSettings');
  await page.reload({ waitUntil: 'networkidle0' });
  await page.click('#settingsBtn'); await page.click('#settingsNavAgent');
  await visible('#agentExistingCard');
  assert.equal(await page.$eval('#agentRoleEnabled', node => node.checked), false);
  assert.equal(await page.$('#agentWelcome'), null);
  pass('closing cancels generation; disabled saved cards survive reload and remain editable');

  await page.click('#agentDesign');
  await page.setViewport({ width: 360, height: 640 });
  await page.screenshot({ path: path.join(scratch, 'narrow-design.png') });
  assert.equal(await page.$eval('.settings-box', node => node.scrollWidth <= node.clientWidth + 1), true);
  assert.equal(await page.$eval('.settings-panes', node => node.scrollWidth <= node.clientWidth + 1), true);
  const narrowFrame = await frame();
  await page.click('#agentBuilderBack');
  await page.click('#agentViewCard');
  assert.deepEqual(await frame(), narrowFrame);
  await page.screenshot({ path: path.join(scratch, 'narrow-card.png') });
  await page.waitForFunction(() => [...document.querySelectorAll('#agentCardEditor textarea')].filter(n => n.getClientRects().length).every(n => n.scrollHeight <= n.clientHeight + 1));
  pass('the wizard, overview and editor keep a fixed frame and fit narrow screens without overflow');

  await page.click('#closeSettings');
  await page.evaluate(() => {
    const profile = JSON.parse(localStorage.getItem('reader.agent.profile.v1'));
    delete profile.customized; localStorage.setItem('reader.agent.profile.v1', JSON.stringify(profile));
  });
  await page.reload({ waitUntil: 'networkidle0' });
  await page.click('#settingsBtn'); await page.click('#settingsNavAgent'); await visible('#agentExistingCard');
  pass('existing cards created before this redesign are recognized without a migration write');

  await page.click('#closeSettings');
  await page.evaluateOnNewDocument(() => localStorage.setItem('reader.locale', 'zh-CN'));
  await page.setViewport({ width: 1400, height: 960 });
  await page.reload({ waitUntil: 'networkidle0' });
  await page.click('#settingsBtn'); await page.click('#settingsNavAgent');
  await page.screenshot({ path: path.join(scratch, 'overview-zh.png') });
  await page.click('#agentDesign');
  await page.screenshot({ path: path.join(scratch, 'design-zh.png') });
  assert.equal(await page.$eval('#agentCardQuestion', node => node.textContent), '你希望我的性格是什么样的？');
  assert.equal(await page.$eval('#agentCardChoices button', node => getComputedStyle(node).flexDirection), 'row');
  await choice(0);
  await page.screenshot({ path: path.join(scratch, 'design-zh-selected.png') });
  pass('Chinese and English character screens are localized');

  await page.click('#closeSettings');
  await page.evaluate(() => { localStorage.removeItem('reader.agent.profile.v1'); localStorage.removeItem('reader.agent.name'); });
  await page.reload({ waitUntil: 'networkidle0' });
  await page.click('#settingsBtn'); await page.click('#settingsNavAgent');
  await page.click('#agentModeCard'); await page.click('#agentProfileSave'); await idle();
  await visible('#agentCustomize');
  assert.equal((await saved()).customized, false, 'switching mode alone does not create a custom card');
  await page.click('#agentCustomize');
  await page.evaluate(async () => { (await import('/js/ai.js')).Settings.data.hasApiKey = false; });
  await page.click('#agentWriteCard'); await visible('#agentCardEditor');
  await page.click('#agentProfileSave'); await idle();
  assert.equal((await saved()).customized, true, 'a deliberately saved default card is still a completed card');
  await visible('#agentExistingCard');
  assert.equal(await page.evaluate(() => __mockChatRequests.length), 0);
  pass('manual cards work without a model, including unchanged defaults; mode toggles alone do not mark customization complete');
});
